"""Import a stock-take result Excel exported by the previous (artifact) app as a CLOSED monthly stock take.

    python3 tools/import_prev_result.py <result.xlsx> <out.sql> [--name "..."]

Reads sheets Counts (who keyed what), Variance (system stock + unit cost per batch) and Summary (MB52 tie-out).
Writes one SQL script that, in one transaction:
  - creates the stock take (status closed, total, single count, good stock, no KPI month),
  - loads its system stock (sys_stock) and MB52 tie-out (mb52_meta),
  - creates one submitted Ops count per warehouse + person, with the lines as keyed.
Warehouses that are not in the app (e.g. NDD Perak) are skipped. Nothing existing is changed, except SKUs the app
doesn't know yet, which are added with the file's description and pack sizes.
A line keyed in cartons/boxes keeps cartons/boxes only when the app's pack size for that SKU is the same as the file's;
otherwise its total pieces are stored, so the totals always equal the file.
"""
import sys, re, json, datetime, hashlib, openpyxl

src, out = sys.argv[1], sys.argv[2]
name = sys.argv[sys.argv.index("--name") + 1] if "--name" in sys.argv else "Month-end stock take Nov 2026 (previous app)"
wb = openpyxl.load_workbook(src, data_only=True)
MYT = datetime.timezone(datetime.timedelta(hours=8))
MON = {m: i + 1 for i, m in enumerate(["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"])}

def ts(s, year):
    m = re.match(r"(\d+) (\w{3}), (\d+):(\d+) ([ap]m)", s or "")
    if not m: return None
    h = int(m[3]) % 12 + (12 if m[5] == "pm" else 0)
    return datetime.datetime(year, MON[m[2]], int(m[1]), h, int(m[4]), tzinfo=MYT).isoformat()

def batch(b):
    b = "" if b is None else str(b).strip()
    m = re.match(r"^(\d{2})/(\d{4})$", b)
    return f"{m[2]}-{m[1]}" if m else b

def num(x): return None if x in (None, "") else float(x)

# MB52 tie-out
tie, loaded = {}, None
for r in wb["Summary"].iter_rows(values_only=True):
    a = str(r[0] or "")
    if a.startswith("MB52 TIE-OUT"): loaded = a.split("upload of ")[-1]
    elif a.startswith("Good stock used as System"): tie["goodV"] = r[1]
    elif a.startswith("Excluded: Blocked"): tie["blockedV"] = r[1]
    elif a.startswith("Excluded: bad-stock"): tie["badLocV"] = r[1]
    elif a.startswith("Excluded: Stock in Transit"): tie["transitV"] = r[1]
    elif a.startswith("Excluded: plants not in branch list"): tie["skippedV"] = r[1]
counts = [r for r in wb["Counts"].iter_rows(min_row=2, values_only=True) if r[0] and r[0] != "TOTAL"]
var = [r for r in wb["Variance"].iter_rows(min_row=2, values_only=True) if r[0] and r[0] != "TOTAL"]
year = 2026
times = sorted(t for t in (ts(r[14], year) for r in counts) if t)
loaded_at = ts(loaded, year) or times[0]

skus, sysrows = {}, []
for r in var:
    skus.setdefault(r[1], {"code": str(r[1]), "desc": r[2] or "", "per": num(r[10]), "box": num(r[11])})
    if r[16] is not None: sysrows.append({"b": r[0], "c": str(r[1]), "bt": batch(r[3]), "q": float(r[16]), "u": num(r[18])})
    # counted where SAP has no stock: keep the file's unit cost (a zero-quantity row), so the value matches the file
    elif r[18] is not None: sysrows.append({"b": r[0], "c": str(r[1]), "bt": batch(r[3]), "q": 0.0, "u": num(r[18])})
sess = {}
for r in counts:
    k = (r[0], r[2] or "")
    s = sess.setdefault(k, {"branch": r[0], "member": r[2] or "", "lines": {}, "t": []})
    t = ts(r[14], year); s["t"].append(t)
    b = batch(r[5])
    s["lines"][f"{r[3]}|{b}"] = {"code": str(r[3]), "batch": b, "ctn": num(r[6]), "box": num(r[7]), "pcs": num(r[8]),
                                 "per": num(r[9]), "perBox": num(r[10]), "total": num(r[11]), "remark": r[12] or "", "t": t}
    skus.setdefault(r[3], {"code": str(r[3]), "desc": r[4] or "", "per": num(r[9]), "box": num(r[10])})
sessions = []
for (b, m), s in sorted(sess.items()):
    dev = "import-" + hashlib.sha1(f"{b}|{m}".encode()).hexdigest()[:12]
    sessions.append({"branch": b, "member": m, "device": dev, "lines": s["lines"], "start": min(s["t"]), "end": max(s["t"])})
payload = {"name": name, "opened": loaded_at, "closed": times[-1], "loaded": loaded_at, "source": re.sub(r"^[0-9a-f]{8}-", "", src.split("/")[-1]),
           "meta": dict(tie, imported=True, source=re.sub(r"^[0-9a-f]{8}-", "", src.split("/")[-1]), skipped=[], stockType="good"),
           "skus": list(skus.values()), "sys": sysrows, "sessions": sessions}
P = json.dumps(payload, ensure_ascii=False).replace("$IMP$", "")

sql = f"""-- generated by tools/import_prev_result.py from {payload['source']}
do $IMP$
declare p jsonb := $J${P}$J$::jsonb; tk uuid; s jsonb; l record; keep boolean; skipped text[];
begin
  if exists (select 1 from public.stock_takes where name = p ->> 'name') then raise exception 'Already imported: %', p ->> 'name'; end if;
  insert into public.skus (code, descr, per, per_box)
    select x ->> 'code', x ->> 'desc', (x ->> 'per')::numeric, (x ->> 'box')::numeric from jsonb_array_elements(p -> 'skus') x
    on conflict (code) do nothing;
  insert into public.stock_takes (name, started_at, closed, status, scope, mode, kind, stock_type, opened_at, closed_at)
    values (p ->> 'name', (p ->> 'opened')::timestamptz, true, 'closed', 'total', 'single', 'monthly', 'good', (p ->> 'opened')::timestamptz, (p ->> 'closed')::timestamptz)
    returning id into tk;
  insert into public.sys_stock (take_id, branch, code, batch, qty, unit_cost)
    select tk, x ->> 'b', x ->> 'c', x ->> 'bt', (x ->> 'q')::numeric, (x ->> 'u')::numeric
    from jsonb_array_elements(p -> 'sys') x where exists (select 1 from public.branches br where br.name = x ->> 'b');
  insert into public.mb52_meta (take_id, data, loaded_at) values (tk, p -> 'meta', (p ->> 'loaded')::timestamptz);
  for s in select * from jsonb_array_elements(p -> 'sessions') loop
    if not exists (select 1 from public.branches br where br.name = s ->> 'branch') then skipped := array_append(skipped, s ->> 'branch'); continue; end if;
    insert into public.count_sessions (take_id, device_id, branch, role, data, status, started_at, updated_at, submitted_at)
    values (tk, s ->> 'device', s ->> 'branch', 'ops',
      jsonb_build_object('member', s ->> 'member', 'names', jsonb_build_array(s ->> 'member'), 'imported', true, 'lines',
        (select coalesce(jsonb_object_agg(e.key,
           case when coalesce((e.value ->> 'ctn')::numeric, 0) = 0 and coalesce((e.value ->> 'box')::numeric, 0) = 0
                  or (((sk.per = (e.value ->> 'per')::numeric) or coalesce((e.value ->> 'ctn')::numeric, 0) = 0)
                      and ((sk.per_box = (e.value ->> 'perBox')::numeric) or coalesce((e.value ->> 'box')::numeric, 0) = 0))
                then jsonb_build_object('code', e.value ->> 'code', 'batch', e.value ->> 'batch', 'ctn', e.value -> 'ctn', 'box', e.value -> 'box', 'pcs', e.value -> 'pcs', 'remark', e.value ->> 'remark', 't', e.value ->> 't')
                else jsonb_build_object('code', e.value ->> 'code', 'batch', e.value ->> 'batch', 'ctn', null, 'box', null, 'pcs', e.value -> 'total',
                       'remark', trim(coalesce(e.value ->> 'remark', '') || ' [keyed ' || coalesce(e.value ->> 'ctn', '0') || ' ctn ' || coalesce(e.value ->> 'box', '0') || ' box ' || coalesce(e.value ->> 'pcs', '0') || ' pcs]'), 't', e.value ->> 't') end), '{{}}'::jsonb)
         from jsonb_each(s -> 'lines') e left join public.skus sk on sk.code = e.value ->> 'code')),
      'submitted', (s ->> 'start')::timestamptz, (s ->> 'end')::timestamptz, (s ->> 'end')::timestamptz);
  end loop;
  raise notice 'imported % as %, skipped warehouses %', p ->> 'name', tk, skipped;
end $IMP$;
"""
open(out, "w").write(sql)
print(f"{len(sessions)} counts, {sum(len(s['lines']) for s in sessions)} lines, {len(sysrows)} system rows, {len(skus)} SKUs -> {out} ({len(sql)//1024} KB)")
